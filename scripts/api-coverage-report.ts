// Writes docs/github-api/COVERAGE.md from the inventory and the decisions in src/github/api-coverage.ts.
// Run: npx tsx scripts/api-coverage-report.ts
import { readFileSync, writeFileSync } from "node:fs";
import { CATEGORY_DECISIONS, OPERATIONS, type Decision } from "../src/github/api-coverage.ts";

interface Operation { id: string; api: string; category: string }
const dir = new URL("../docs/github-api/", import.meta.url);
const inv = JSON.parse(readFileSync(new URL("inventory.json", dir), "utf8")) as { restVersion: string; generatedAt: string; operations: Operation[] };
const decide = (o: Operation): Decision => OPERATIONS[o.id] ?? CATEGORY_DECISIONS[`${o.api}:${o.category}`];

const rows = inv.operations.map((o) => ({ o, d: decide(o) }));
const count = (k: Decision["kind"]) => rows.filter((x) => x.d.kind === k).length;
const group = (k: "gesture" | "read") => {
  const by = new Map<string, string[]>();
  for (const { o, d } of rows) if (d.kind === k) {
    const text = d.kind === "gesture" ? d.gesture : d.kind === "read" ? d.shows : "";
    by.set(text, [...(by.get(text) ?? []), o.id]);
  }
  return [...by].map(([text, ids]) => `- ${text}\n  ${ids.map((i) => `\`${i}\``).join(", ")}`).join("\n");
};

const md = `# GitHub API coverage

Generated by \`scripts/api-coverage-report.ts\` from \`inventory.json\` (${inv.operations.length} operations, REST description ${inv.restVersion}, read on ${inv.generatedAt}) and the decisions in \`src/github/api-coverage.ts\`. \`src/github/api-coverage.test.ts\` fails if any operation has no decision.

| Decision | Operations |
|---|---:|
| A game gesture (writes to GitHub) | ${count("gesture")} |
| Read to build the world | ${count("read")} |
| Later (contributors' version, live version, ideas) | ${count("later")} |
| Out of scope, with a reason | ${count("out")} |

## Gestures

${group("gesture")}

## Reads

${group("read")}
`;
writeFileSync(new URL("COVERAGE.md", dir), md);
console.log(`COVERAGE.md: ${count("gesture")} gestures, ${count("read")} reads, ${count("later")} later, ${count("out")} out`);
